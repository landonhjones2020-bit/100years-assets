"""Write game/shared/Config/CavePieces.luau from the A6 cave pieces' sidecars (exports/Caves/*.json).

    python3 tools/cave_config.py

The pieces are made in Blender (generators/Caves/cavelib.py); their size, exits and weights come
from there, so the cave planner (Shared.Rules.Deep) and the art can't drift apart. Run it after
re-exporting a piece.
"""
from __future__ import annotations

import glob
import json
import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(REPO, "game", "shared", "Config", "CavePieces.luau")

TEXT = {
    "Entry": "The mouth: a rock face where the dug cell's back wall was, and a short tunnel.",
    "Tunnel": "A straight run.",
    "Junction": "The way splits left and right.",
    "Pocket": "A small dead end with two finds.",
    "Chamber": "A room with three finds, a way on and a way to the left.",
    "Cavern": "A big dead end with a nest spot and four finds.",
    "Drop": "The floor falls away down a slope to a lower tunnel.",
    "CrewPocket": "Where a Lost Crew is trapped, guarded.",
}
ORDER = ["Entry", "Tunnel", "Junction", "Pocket", "Chamber", "Cavern", "Drop", "CrewPocket"]
BANDS = {"Mines": "Mines", "FloodedCaverns": "Flooded"}


def num(v: float) -> str:
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(v) -> str:
    return "{ " + ", ".join(num(x) for x in v) + " }"


def main() -> str:
    docs = {}
    for path in sorted(glob.glob(os.path.join(REPO, "exports", "Caves", "Cave_*.json"))):
        d = json.load(open(path))
        docs[d["asset"]] = d
    lines = []
    order = []
    for band_id, band in BANDS.items():
        for kind in ORDER:
            asset = f"Cave_{band}_{kind}"
            d = docs.get(asset)
            if not d:
                continue
            meta = d["meta"]
            exits = sorted((k, v) for k, v in d["sockets"].items() if k.startswith("Exit"))
            ident = f"{band}{kind}"
            order.append(ident)
            ex = ", ".join("{ P = " + vec(v["p"]) + f", Yaw = {num(v['yaw'])} " + "}" for _, v in exits)
            finds = sum(1 for k in d["sockets"] if k.startswith("Find"))
            lines.append(
                f"\t\t{ident} = {{ Name = \"{band} {kind.lower()}\", Band = \"{band_id}\", Kind = \"{kind}\", Asset = \"{asset}\",\n"
                f"\t\t\tWeight = {num(meta['weight'])}, Finds = {finds}, Box = {{ Min = {vec(meta['box']['min'])}, Max = {vec(meta['box']['max'])} }},\n"
                f"\t\t\tExits = {{ {ex} }}, Text = \"{TEXT[kind]}\" }},")
    body = "\n".join(lines)
    order_s = ", ".join(f'"{o}"' for o in order)
    src = f'''--!strict
--[[
	CavePieces: the hand-made pieces caves are put together from (bible Sections 6 and 12; A6;
	Prompt 17). Generated by tools/cave_config.py from the pieces' sidecars (exports/Caves):
	don't edit by hand, change generators/Caves and run the tool.

	Each piece is entered at its pivot (the floor centre of a 14 x 12 opening, facing -Z into the
	piece) and leaves through its Exits (an opening's floor centre; Yaw: the way out, so 0 is -Z).
	Box: the room it takes (Roblox space from the pivot) so pieces never overlap. Weight: how often
	the planner picks it (0: placed on purpose, Entry and CrewPocket). Finds: its Find sockets.
]]

local Check = require(script.Parent.Parent.Utilities.Check)
local F = require(script.Parent._Fields)

local Vec = Check.array(Check.number(), 3)

return {{
	Schema = Check.shape({{
		Name = F.Name,
		Band = Check.ref("DepthBands"),
		Kind = Check.enum({{ "Entry", "Tunnel", "Junction", "Pocket", "Chamber", "Cavern", "Drop", "CrewPocket" }}),
		Asset = Check.string(60),
		Weight = Check.number(),
		Finds = Check.integer(0, 8),
		Box = Check.shape({{ Min = Vec, Max = Vec }}),
		Exits = Check.array(Check.shape({{ P = Vec, Yaw = Check.number() }}), 4),
		Text = F.Short,
	}}),
	Order = {{ {order_s} }},
	Entries = {{
{body}
	}},
}}
'''
    with open(OUT, "w") as f:
        f.write(src)
    return f"{OUT}: {len(order)} pieces"


if __name__ == "__main__":
    print(main())
